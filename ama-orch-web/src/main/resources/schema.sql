    is_member BOOLEAN DEFAULT TRUE,
    is_part_leader BOOLEAN DEFAULT FALSE,
    is_concert_master BOOLEAN DEFAULT FALSE,
    coordinator VARCHAR(64),
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_datetime TIMESTAMP,
    delete_datetime TIMESTAMP,
    update_by VARCHAR(64) DEFAULT 'system',
    PRIMARY KEY (person_id, oconcert_id),
    CONSTRAINT fk_concert_member_person FOREIGN KEY (person_id) REFERENCES person (person_id),
    CONSTRAINT fk_concert_member_concert FOREIGN KEY (oconcert_id) REFERENCES concert (concert_id)
);
CREATE INDEX IF NOT EXISTS idx_concert_member_concert ON concert_member (oconcert_id);
CREATE INDEX IF NOT EXISTS idx_stage_layout_seat_layout ON stage_layout_seat (layout_id);
