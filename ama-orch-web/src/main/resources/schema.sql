CREATE INDEX IF NOT EXISTS idx_concert_lesson_concert ON concert_lesson (concert_id);
-- =============================================
-- rehea_analysis_data テーブル（リハーサル音声解析結果）
--   analysis_id は YouTube/SRT の字幕データハッシュ、またはリアルタイム取得時刻。
-- =============================================
CREATE TABLE IF NOT EXISTS rehea_analysis_data (
    analysis_id VARCHAR(64) NOT NULL,
    lesson_id BIGINT,
    concert_id VARCHAR(12),
    branch_no INT,
    lesson_date DATE,
    download_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (analysis_id),
    CONSTRAINT fk_rehea_analysis_data_lesson FOREIGN KEY (lesson_id) REFERENCES concert_lesson (id),
    CONSTRAINT fk_rehea_analysis_data_concert FOREIGN KEY (concert_id) REFERENCES concert (concert_id)
);
-- =============================================
-- rehea_analysis_data_member テーブル（解析結果の指摘明細）
-- =============================================
CREATE TABLE IF NOT EXISTS rehea_analysis_data_member (
    analysis_id VARCHAR(64) NOT NULL,
    lesson_at BIGINT NOT NULL,
    measure VARCHAR(256),
    instrument VARCHAR(256),
    instruction TEXT,
    PRIMARY KEY (analysis_id, lesson_at),
    CONSTRAINT fk_rehea_analysis_data_member_analysis FOREIGN KEY (analysis_id) REFERENCES rehea_analysis_data (analysis_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_rehea_analysis_data_lesson ON rehea_analysis_data (lesson_id);
CREATE INDEX IF NOT EXISTS idx_rehea_analysis_data_member_analysis ON rehea_analysis_data_member (analysis_id);
