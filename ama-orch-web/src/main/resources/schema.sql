-- =============================================
-- stage_layout テーブル（舞台配置マスタ）
--   concert_program.layout_id から参照される。
--   1つの配置を複数の曲で使い回せるよう、独立したマスタとして持つ。
-- =============================================
CREATE TABLE IF NOT EXISTS stage_layout (
    layout_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layout_name VARCHAR(64) NOT NULL,
    orch_name VARCHAR(64),
    stage_width INT NOT NULL,
    stage_depth INT NOT NULL,
    memo TEXT,
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_datetime TIMESTAMP,
    delete_datetime TIMESTAMP,
    update_by VARCHAR(64) DEFAULT 'system'
);
-- =============================================
-- stage_layout_seat テーブル（舞台配置の座席 = stage_layout の子テーブル）
--   座標系: 舞台を真上から見た図。原点は左上、x は下手→上手、y は舞台奥→客席側。
--           つまり y が大きいほど客席に近い（指揮者は手前＝y の大きい側）。
--   rotation: 正面の向き。0 = 画面上（舞台奥）向き、時計回りに 0-359 度。
--             客席を向く場合は 180。既定では全員が指揮者を向く角度を入れる。
-- =============================================
CREATE TABLE IF NOT EXISTS stage_layout_seat (
    seat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layout_id BIGINT NOT NULL,
    seat_no INT NOT NULL,
    role_type VARCHAR(16) NOT NULL,
    part_code VARCHAR(16),
    part_name VARCHAR(32),
    pult_no INT,
    seat_side VARCHAR(8),
    person_id BIGINT,
    person_name VARCHAR(32),
    pos_x INT NOT NULL,
    pos_y INT NOT NULL,
    rotation INT NOT NULL,
    memo VARCHAR(128),
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_datetime TIMESTAMP,
    delete_datetime TIMESTAMP,
    update_by VARCHAR(64) DEFAULT 'system'
);
-- =============================================
-- orch_member テーブル（団体所属メンバー）
--   レイアウトに割り当てられた人物を、使用団体単位で自動登録する。
-- =============================================
CREATE TABLE IF NOT EXISTS orch_member (
    person_id BIGINT NOT NULL,
    orch_id VARCHAR(6) NOT NULL,
    start_date DATE NOT NULL DEFAULT DATE '1900-01-01',
    end_date DATE,
    main_active_instrument VARCHAR(32),
    is_member BOOLEAN DEFAULT TRUE,
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_datetime TIMESTAMP,
    delete_datetime TIMESTAMP,
    update_by VARCHAR(64) DEFAULT 'system',
    PRIMARY KEY (person_id, orch_id),
    CONSTRAINT fk_orch_member_person FOREIGN KEY (person_id) REFERENCES person (person_id),
    CONSTRAINT fk_orch_member_orch FOREIGN KEY (orch_id) REFERENCES orch_mst (orch_id)
);
CREATE INDEX IF NOT EXISTS idx_orch_member_orch ON orch_member (orch_id);
-- =============================================
-- concert_member テーブル（演奏会出演メンバー）
--   oconcert_id は concert.concert_id を参照する演奏会ID。
-- =============================================
