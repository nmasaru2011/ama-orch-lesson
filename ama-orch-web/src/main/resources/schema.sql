CREATE TABLE IF NOT EXISTS rehea_analysis_correction_mst (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sort_order INT NOT NULL,
    wrong_text VARCHAR(255) NOT NULL,
    correct_text VARCHAR(255) NOT NULL,
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_datetime TIMESTAMP,
    delete_datetime TIMESTAMP,
    update_by VARCHAR(64) DEFAULT 'system',
    UNIQUE (wrong_text)
);
CREATE TABLE IF NOT EXISTS rehea_analysis_instrument_keyword_mst (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name VARCHAR(255) NOT NULL,
    keyword VARCHAR(255) NOT NULL,
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_datetime TIMESTAMP,
    delete_datetime TIMESTAMP,
    update_by VARCHAR(64) DEFAULT 'system',
    UNIQUE (canonical_name, keyword)
);
CREATE TABLE IF NOT EXISTS rehea_analysis_include_keyword_mst (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword VARCHAR(255) NOT NULL,
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_datetime TIMESTAMP,
    delete_datetime TIMESTAMP,
    update_by VARCHAR(64) DEFAULT 'system',
