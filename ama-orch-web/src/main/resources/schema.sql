-- =============================================
-- concert_lesson テーブル（練習データ）
-- =============================================
CREATE TABLE IF NOT EXISTS concert_lesson (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id VARCHAR(12) NOT NULL,
    branch_no INT NOT NULL,
    lesson_date DATE NOT NULL,
    lesson_start_time_str VARCHAR(32),
    lesson_end_time_str VARCHAR(32),
    lesson_start_time TIMESTAMP,
    lesson_end_time TIMESTAMP,
    place_name VARCHAR(64),
    contain VARCHAR(256),
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_datetime TIMESTAMP,
